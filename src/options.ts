import {
  booleanOption,
  compositeOption,
  type ArgumentOption,
  nullableOption,
  valueOption,
} from './clio.js';
import { ConverterOptions } from './options_converter.js';

/** Encapsulates a Confluence page ID. */
export type ConfluencePageID = string;

/** Encapsulates a snippet of Markdown text. */
export type Markdown = string;

/** Behavior for synchronizing page attachments. */
export type AttachmentSyncMode = 'full' | 'upsert' | 'create';

/**
 * Options that control how page content is generated and synchronized.
 *
 * @param rootPage Confluence page to assume root page role for publishing a directory of Markdown files.
 * @param keepHierarchy Whether to maintain source directory structure when exporting to Confluence.
 * @param titlePrefix String to prepend to Confluence page title for each published page.
 * @param generatedBy Text to use as the generated-by prompt (or `undefined` to omit a prompt).
 * @param attachmentSync Behavior for synchronizing page attachments.
 * @param skipUpdate Whether to skip saving Confluence page ID in Markdown files.
 * @param converter Options for converting an HTML tree into Confluence Storage Format.
 */
export class ProcessorOptions {
  static readonly fields: readonly ArgumentOption[] = [
    valueOption(
      'rootPage',
      { type: 'text', metavar: 'CONFLUENCE_PAGE_ID' },
      'Confluence page to act as initial parent for creating new pages. Defaults to space home page.',
    ),
    booleanOption(
      'keepHierarchy',
      'Maintain source directory structure when exporting to Confluence.',
      'Flatten directories with no `index.md` or `README.md` when exporting to Confluence.',
    ),
    nullableOption(
      'titlePrefix',
      { type: 'text' },
      'String to prepend to Confluence page title for each published page.',
      'Use Markdown title to synchronize page.',
    ),
    nullableOption(
      'generatedBy',
      { type: 'text', metavar: 'MARKDOWN' },
      'Add prompt to pages.',
      "Do not add 'generated by a tool' prompt to pages.",
    ),
    valueOption(
      'attachmentSync',
      { type: 'choice', choices: ['full', 'upsert', 'create'] },
      'Synchronization mode for Confluence page attachments.',
    ),
    booleanOption(
      'skipUpdate',
      'Skip saving Confluence page ID in Markdown files.',
      'Inject published Confluence page ID in Markdown files.',
    ),
    compositeOption('converter', ConverterOptions, true),
  ];

  constructor(
    public rootPage?: ConfluencePageID,
    public keepHierarchy = false,
    public titlePrefix?: string,
    public generatedBy: Markdown | undefined = 'This page has been generated with a tool.',
    public attachmentSync: AttachmentSyncMode = 'full',
    public skipUpdate = false,
    public converter: ConverterOptions = new ConverterOptions(),
  ) {}
}

export type DocumentOptions = ProcessorOptions;
